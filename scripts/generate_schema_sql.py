def main():
    out = Path(__file__).resolve().parents[1] / "db" / "migration" / "V1__labelhub_init_schema.sql"
    lines = [
        "-- LabelHub 初始化 DDL",
        "-- 来源: docs/database-design.md",
        "-- MySQL 8.0+ / InnoDB / utf8mb4_0900_ai_ci",
        "-- 主键由应用侧发号（雪花/Leaf），非 AUTO_INCREMENT",
        "",
        "SET NAMES utf8mb4;",
        "SET FOREIGN_KEY_CHECKS = 0;",
        "",
    ]
    sections = [
        ("-- ========== 第一批：系统基础 ==========", ORDER[:14]),
        ("-- ========== 第二批：任务与模板 ==========", ORDER[14:22]),
        ("-- ========== 第三批：生产主链路 ==========", ORDER[22:31]),
        ("-- ========== 第四批：导出、验收、结算、文件、通知、统计、运行支撑 ==========", ORDER[31:]),
    ]
    for header, names in sections:
        lines.append(header)
        lines.append("")
        for name in names:
            t = by_name[name]
            lines.append(create_table(t[0], t[1], t[2] if len(t) > 2 else None, t[3] if len(t) > 3 else None))
            lines.append("")
    lines.append("-- ========== 物理外键（仅低频强约束表） ==========")
    lines.append("")
    for table, cname, col, ref_table, ref_col in FK_CONSTRAINTS:
        lines.append(
            f"ALTER TABLE `{table}` ADD CONSTRAINT `{cname}` "
            f"FOREIGN KEY (`{col}`) REFERENCES `{ref_table}` (`{ref_col}`);"
        )
    lines.append("")
    lines.append("SET FOREIGN_KEY_CHECKS = 1;")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out} ({len(lines)} lines, {len(ORDER)} tables, {len(FK_CONSTRAINTS)} FKs)")


if __name__ == "__main__":
    main()
