def create_table(name: str, cols: list[str], uks: list[tuple[str, str]] | None = None, idxs: list[tuple[str, str]] | None = None) -> str:
    parts = [f"CREATE TABLE `{name}` (", BASE + ","]
    parts.extend(f"  {c}," for c in cols)
    parts.append("  PRIMARY KEY (`id`)")
    keys: list[str] = []
    if uks:
        keys.extend(f"  UNIQUE KEY `{n}` ({c})" for n, c in uks)
    if idxs:
        keys.extend(f"  KEY `{n}` ({c})" for n, c in idxs)
    if keys:
        parts[-1] += ","
        parts.extend(k + ("," if i < len(keys) - 1 else "") for i, k in enumerate(keys))
    parts.append(") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;")
    return "\n".join(parts)


